// Reference rows are loose: many qty fields are textual ("33.33%", "As per formula").
// We keep them legible by storing the original qty text in `unit` and `qty=0`.
const r = (name: string, cat: RMCategory, qtyText: string, part: string): RMItem => ({
  name,
  cat,
  qty: 0,
  unit: qtyText,
  part,
});

